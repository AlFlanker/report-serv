import pg from 'pg';

const { Pool } = pg;

export function validateSchema(schema) {
  if (typeof schema !== 'string' || !/^[a-z_][a-z0-9_]{0,62}$/.test(schema) || schema.startsWith('pg_') || schema === 'information_schema') {
    throw new Error('DATABASE_SCHEMA must be a lowercase PostgreSQL identifier (1–63 characters), outside system schemas');
  }
  return schema;
}

/** Each transaction owns one connection; another request cannot commit its work. */
export async function openDatabase({
  connectionString = process.env.DATABASE_URL,
  schema = process.env.DATABASE_SCHEMA ?? 'public',
  acquireLock = false,
} = {}) {
  validateSchema(schema);
  if (!connectionString) throw new Error('DATABASE_URL is required');
  const pool = new Pool({
    connectionString,
    options: `-c search_path=${schema} -c timezone=UTC`,
    max: 10,
    connectionTimeoutMillis: 10_000,
    idleTimeoutMillis: 30_000,
    statement_timeout: 30_000,
    application_name: 'report-serv',
  });
  const controller = new AbortController();
  // Idle connection failures are handled by pg (the connection is removed).
  // A dedicated advisory-lock session failure is fatal to this service owner.
  pool.on('error', () => {});
  let owner;
  let closed = false;
  let closePromise;
  const assertOpen = () => {
    controller.signal.throwIfAborted();
    if (closed) throw new Error('Database is closed');
  };
  async function transaction(operation) {
    assertOpen();
    const client = await pool.connect();
    try {
      assertOpen();
      await client.query('BEGIN');
      const result = await operation(client);
      assertOpen();
      await client.query('COMMIT');
      return result;
    } catch (error) {
      await client.query('ROLLBACK').catch(() => {});
      throw error;
    } finally { client.release(); }
  }
  async function close() {
    if (closePromise) return closePromise;
    closed = true;
    closePromise = (async () => {
      if (owner) {
        // Await the normal unlock so an immediately restarted service does
        // not race asynchronous socket closure. Destroy is the fallback when
        // PostgreSQL became unreachable and UNLOCK could not be sent.
        await owner.query('SELECT pg_advisory_unlock(hashtext(current_database()),hashtext($1))',
          [`report-serv-owner:${schema}`]).catch(() => {});
        owner.release(true);
        owner = undefined;
      }
      await pool.end();
    })();
    return closePromise;
  }
  try {
    if (acquireLock) {
      owner = await pool.connect();
      owner.on('error', error => controller.abort(error));
      const locked = await owner.query(
        'SELECT pg_try_advisory_lock(hashtext(current_database()),hashtext($1)) AS acquired',
        [`report-serv-owner:${schema}`],
      );
      if (!locked.rows[0].acquired) throw Object.assign(new Error('Another report service or migration already owns this database schema'), { code: 'DATABASE_IN_USE' });
    }
    await transaction(async client => {
      await client.query('SELECT pg_advisory_xact_lock(hashtext(current_database()),hashtext($1))', [`report-serv-schema:${schema}`]);
      await client.query(`CREATE SCHEMA IF NOT EXISTS "${schema}"`);
      await client.query(`
        CREATE TABLE IF NOT EXISTS schema_migrations (
          version INTEGER PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
        );
        CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);
        CREATE TABLE IF NOT EXISTS jobs (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          report_id TEXT NOT NULL, parameters JSONB NOT NULL,
          status TEXT NOT NULL CHECK (status IN ('queued','running','completed','failed')),
          stage TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL,
          started_at TIMESTAMPTZ, completed_at TIMESTAMPTZ, expires_at TIMESTAMPTZ,
          result_metadata JSONB, error_json JSONB, ready_at TIMESTAMPTZ
        );
        CREATE INDEX IF NOT EXISTS jobs_created ON jobs(created_at DESC,id DESC);
        CREATE INDEX IF NOT EXISTS jobs_status ON jobs(status);
        CREATE TABLE IF NOT EXISTS notifications (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          job_id INTEGER NOT NULL REFERENCES jobs(id), title TEXT NOT NULL,
          created_at TIMESTAMPTZ NOT NULL, is_read BOOLEAN NOT NULL DEFAULT false
        );
        CREATE TABLE IF NOT EXISTS object_cleanup (
          object_key TEXT PRIMARY KEY, bucket TEXT NOT NULL,
          reason TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL
        );
        INSERT INTO schema_migrations(version) VALUES(1) ON CONFLICT DO NOTHING;
      `);
    });
    return {
      schema,
      signal: controller.signal,
      query(text, values) { assertOpen(); return pool.query(text, values); },
      transaction,
      close,
    };
  } catch (error) {
    await close();
    throw error;
  }
}
